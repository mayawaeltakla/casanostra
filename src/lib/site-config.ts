/**
 * واجهة الخدمة — تحتوي البيانات الكاملة لعرض صفحة خدمة مفصّلة.
 */
export interface Service {
  slug: string;
  title: string;
  shortDescription: string;     // وصف قصير للبطاقات
  icon: string;                // اسم أيقونة lucide-react
  longDescription: string;     // فقرة تعريفية كاملة في رأس صفحة الخدمة
  heroImage: string;           // صورة Unsplash كبيرة للقسم العلوي
  /** موضع قصّ صورة الغلاف (object-position) — يضبط إبراز موضوع الصورة دون قصّه */
  heroImagePosition?: string;
  duration: string;            // المدة (مثلاً: "يوم كامل" أو "حسب الطلب")
  priceFrom?: string;           // السعر التقريبي (للعرض فقط)
  features: { title: string; description: string }[];  // مميزات الخدمة
  included: string[];           // المشمولات
  excluded: string[];           // غير المشمولات
  galleryImages: string[];      // صور المعرض (3-4 صور)
  /** عنوان تسويقي (عربي فقط حالياً) — يظهر أعلى أو أسفل محتوى صفحة الخدمة */
  marketing?: { title: string; subtitle: string; position: "top" | "bottom" };

  /* ==================================================================
   * حقول اختيارية للأقسام الإضافية في صفحة الخدمة.
   * تُعرَّف بالعربية هنا، وتُترجَم في `src/i18n/service-details.ts`
   * لبقية اللغات (نفس نمط features / included / excluded).
   * الخدمات التي لا تعرّفها تُعرض كما هي دون أي قسم إضافي أو تغيير.
   * ================================================================== */

  /** نص بديل (alt) لصورة الغلاف — الافتراضي: عنوان الخدمة المترجَم */
  heroImageAlt?: string;
  /** مواضع قصّ صور المعرض بنفس ترتيبها (الافتراضي: center) */
  galleryImagesPosition?: string[];
  /** نصوص بديلة لصور المعرض بنفس ترتيبها */
  galleryImagesAlt?: string[];
  /** قسم «باقة الخدمات الشاملة» — بطاقات مرقّمة بعنوان ووصف */
  bundle?: { heading: string; items: { title: string; description: string }[] };
  /** قسم الشركاء (الجامعات) — اسم محلي + الاسم الرسمي */
  universities?: {
    heading: string;
    intro: string;
    items: { name: string; official: string }[];
  };
  /**
   * قسم العرض الترويجي.
   * `discount` يُعرَّف هنا مرة واحدة فقط (مصدر مركزي) ويُستخدم لكل اللغات.
   */
  promo?: { heading: string; description: string; discount: string };
}

